#!/usr/bin/env python3
"""Hygiene and index of the `plans/` artefacts.

The workflow in `docs/WORKFLOW.md` hands files, not chat histories, from phase
to phase. For that to hold, the files must be findable and say where things
stand. Both decay silently: an artefact without frontmatter is invisible to
every query, and a spec that is built yet still kept as active is the double
truth `plans/_README.md` is written against.

Two modes, each complete on its own:

    --check    reports the hygiene through `_verdict` (INFO/DRIFT/BLOCK)
    --index    regenerates `plans/INDEX.md`

Why separate: a tool that writes while checking cannot tell whether the tree
was right beforehand. `--check` touches nothing.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _verdict import Level, Ramp, Verdict  # noqa: E402

REPO = Path(__file__).resolve().parent.parent
PLANS = REPO / "plans"
INDEX = PLANS / "INDEX.md"

# `bead` is required because the index renders a bead column: without the field
# there is a gap, and an artefact without a bead is work that shows up in no
# query — `bd ready` does not know it.
REQUIRED = ("status", "implementation_status", "date", "last_reviewed", "bead")
STATUS = {"draft", "accepted", "superseded"}
IMPLEMENTATION = {"none", "partial", "done"}
STALE_AFTER_DAYS = 90

# The index is generated; the header lines live here so that a hand edit stands out.
INDEX_HEADER = """<!-- GENERATED by scripts/plans_registry.py --index — do not edit by hand -->

# plans/INDEX.md

Every artefact under `plans/`, with its two status fields. Generated, never
typed: a hand-kept list of files ages exactly as fast as files are added.

| Artefact | status | implementation_status | last reviewed | Bead |
|---|---|---|---|---|
"""


def _frontmatter(path: Path) -> dict | None:
    """The YAML block at the start of the file, or None if there is none."""
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        return None
    end = text.find("\n---", 4)
    if end == -1:
        return None
    try:
        loaded = yaml.safe_load(text[4:end])
    except yaml.YAMLError:
        return None
    return loaded if isinstance(loaded, dict) else None


def artefacts() -> list[Path]:
    """Every Markdown file under `plans/`, except the generated and explanatory ones."""
    if not PLANS.exists():
        return []
    return sorted(
        p for p in PLANS.rglob("*.md") if p.name not in {"_README.md", "INDEX.md"} and not p.name.startswith("_")
    )


def _age_days(value: object) -> int | None:
    if isinstance(value, dt.date):
        return (dt.date.today() - value).days
    if isinstance(value, str):
        try:
            return (dt.date.today() - dt.date.fromisoformat(value)).days
        except ValueError:
            return None
    return None


def _bead_export_path() -> Path:
    """The ONE access point to the tracker state (bead 1jg.3).

    The monkeypatch convention stays: if REPO points at a fixture repo, the
    (transitional) copy there decides, not the real tracker — a test without a
    tracker must not suddenly read the real state. In the real repo
    `bead_render.render_pfad()` delivers: in CI the preset render, otherwise a
    fresh render — a copy no longer exists since bead 1jg.3.
    """
    if Path(__file__).resolve().parent.parent != REPO:
        return REPO / ".beads" / "issues.jsonl"
    from bead_render import render_pfad  # noqa: E402 — no second access path

    return render_pfad()


def _anzeige(pfad: Path) -> str:
    """Repo-relative where possible — a fresh render lies outside the repo."""
    try:
        return str(pfad.relative_to(REPO))
    except ValueError:
        return str(pfad)


def _bead_statuses(export_path: Path) -> dict[str, str] | None:
    """`id -> status` from the tracker state (JSON Lines, one line per bead).

    The path comes from the ONE access point (bead 1jg.3); this parsing stays
    file reading — the access point decides WHICH file that is.

    Returns None if the state is missing, unreadable, or holds not a single
    usable line -- that is the case in which the coupling check below itself
    measures nothing, and the caller reports it as a finding of its own (BLOCK,
    RB-G7) instead of staying silent.
    """
    if not export_path.exists():
        return None
    statuses: dict[str, str] = {}
    for line in export_path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError:
            continue
        if isinstance(row, dict) and isinstance(row.get("id"), str) and isinstance(row.get("status"), str):
            statuses[row["id"]] = row["status"]
    return statuses or None


# The stock on the day the reverse direction went live (2026-09-15).
#
# By name, not as a number: a valve that carries "the first five" also carries
# the sixth that arrives tomorrow. This way every NEW bead without an artefact
# is DRIFT at once, and only these five wait.
BESTAND_OHNE_ARTEFAKT = frozenset(
    {
        "portfolio-agentic-engineering-ke1k",
        "portfolio-agentic-engineering-nu5a",
        "portfolio-agentic-engineering-twgy.7",
        "portfolio-agentic-engineering-utdf",
        "portfolio-agentic-engineering-wp-l2",
    }
)


def _bestand_ramp(offen: set[str]) -> Ramp:
    """The five legacy cases count as INFO until they are cleared — or the deadline holds.

    Arming at once would mean: `plans-drift` is red from day one, over a state
    this pull request did not create. A gate that is always red gets switched
    off and protects nothing afterwards — the same reasoning as for
    `_praesenz_ramp` in `validate_change_artefacts.py`.

    The target is DRIFT, not INFO: the valve arms itself as soon as it is due,
    without anyone having to catch up here.
    """

    def bestand_geraeumt() -> bool:
        return not (offen & BESTAND_OHNE_ARTEFAKT)

    return Ramp(
        name="bead-ohne-artefakt-bestand",
        condition=(
            "the five beads without an artefact that were running on 2026-09-15 have a "
            "change folder or are no longer 'in_progress' "
            "(2026-11-30 at the latest)"
        ),
        predicate=bestand_geraeumt,
        target=Level.DRIFT,
        until_then=Level.INFO,
        deadline=dt.date(2026, 11, 30),
    )


def check() -> Verdict:
    verdict = Verdict()
    found = artefacts()
    try:
        export_path = _bead_export_path()
    except (FileNotFoundError, RuntimeError) as exc:
        # RuntimeError covers bead_render.RendererNichtMoeglich without loading
        # the access point at import time (the fixture-repo seam above does not
        # need it). No tracker state: the coupling measures nothing.
        bead_statuses = None
        verdict.block(
            "Tracker state not measurable",
            f"The artefact<->bead coupling measures nothing (RB-G7): {exc}",
        )
    else:
        bead_statuses = _bead_statuses(export_path)
        if bead_statuses is None:
            verdict.block(
                f"Tracker render {_anzeige(export_path)} missing or empty",
                "Then it is not the artefact<->bead coupling that is violated, but the "
                "check itself measures nothing (RB-G7). Fix: "
                "`python3 scripts/bead_render.py` shows where the state comes from.",
            )

    if not found:
        # No BLOCK: a freshly set-up repo legitimately has zero artefacts.
        # But no silence either — an empty set is named, not left out,
        # otherwise "green" reads like "checked".
        #
        # And no `return`: the index is checked anyway. An early exit here
        # would mean a tracked index that still lists a deleted artefact goes
        # unnoticed in exactly the case where it is most certainly wrong.
        verdict.info(
            "no artefact under plans/",
            "The workflow is set up and has not run yet.",
        )

    by_name = {str(p.relative_to(REPO)): p for p in found}
    # D4 (spec.md/plan.md): once per folder, not per artefact in it — three
    # identical lines for one folder would be noise.
    ordner_ohne_plan_gemeldet: set[Path] = set()
    # Which beads have an artefact at all. Needed for the reverse direction of
    # the coupling below -- the loop here runs over artefacts and cannot see a
    # bead that never got one.
    beads_mit_artefakt: set[str] = set()

    for path in found:
        rel = str(path.relative_to(REPO))
        meta = _frontmatter(path)

        if meta is None:
            verdict.block(f"{rel}: no readable frontmatter", "Without frontmatter it is invisible to every query.")
            continue

        for field in REQUIRED:
            if field not in meta:
                verdict.block(f"{rel}: field '{field}' missing")
            elif meta.get(field) in (None, ""):
                # "present" and "filled" are not the same thing: a required
                # field that is there but empty (`last_reviewed:`) or
                # explicitly `null` used to be the same blind spot for every
                # downstream check as a missing field -- `last_reviewed: null`
                # thereby silently switched off its own age and readability
                # check (AK-4, spec.md Z3). The two pointers that may carry
                # `null` are `supersedes` and `superseded_by`
                # (plans/_README.md) -- neither is in REQUIRED, and this loop
                # does not affect them.
                verdict.block(f"{rel}: field '{field}' is empty")

        if meta.get("status") not in STATUS | {None}:
            verdict.block(f"{rel}: status '{meta.get('status')}' is none of {sorted(STATUS)}")
        if meta.get("implementation_status") not in IMPLEMENTATION | {None}:
            verdict.block(
                f"{rel}: implementation_status '{meta.get('implementation_status')}' "
                f"is none of {sorted(IMPLEMENTATION)}"
            )

        # Path segments relative to PLANS, not substrings of `rel` (R-3): a
        # directory that happens to be called "changes" -- say
        # `plans/specs/changes/spec.md` -- is not a change. `PLANS` need not be
        # called "plans" either; the test fixture bends that.
        plans_parts = path.relative_to(PLANS).parts
        in_changes = bool(plans_parts) and plans_parts[0] == "changes"
        archived = in_changes and len(plans_parts) > 1 and plans_parts[1] == "archive"

        if in_changes and not archived and meta.get("implementation_status") == "done":
            verdict.drift(
                f"{rel}: built and not archived",
                "Per plans/_README.md the delta belongs in the living spec and the rest in the archive.",
            )

        # D4 (spec.md §7, plan.md §4 S4): if the code moves (implementation_status
        # 'partial' or 'done'), phase 3 has happened — otherwise the plan is the
        # code, and that is the case "The plan is the contract"
        # (docs/WORKFLOW.md §2) is written against. DRIFT rather than BLOCK: the
        # escalation is carried by the `--strict` run (plans-drift), no one
        # else's pull request should go red for it. A folder whose artefacts all
        # carry 'none' is not affected -- no code has moved there.
        if (
            in_changes
            and not archived
            and meta.get("implementation_status") in {"partial", "done"}
            and not (path.parent / "plan.md").exists()
            and path.parent not in ordner_ohne_plan_gemeldet
        ):
            ordner_ohne_plan_gemeldet.add(path.parent)
            verdict.drift(
                f"{path.parent.relative_to(REPO)}/: implementation_status is "
                f"'{meta.get('implementation_status')}', but there is no plan.md",
                "Phase 3 did not happen, or the plan is the code.",
            )

        last_reviewed = meta.get("last_reviewed")
        age = _age_days(last_reviewed)
        if last_reviewed is not None and age is None:
            verdict.drift(
                f"{rel}: last_reviewed '{last_reviewed}' is not a readable date",
                "An unreadable value is a finding, not a reason to skip the check.",
            )
        elif age is not None and age > STALE_AFTER_DAYS and not archived:
            verdict.drift(f"{rel}: not reviewed for {age} days")

        # `date` is parsed the same way as `last_reviewed` — not for the age
        # threshold, only so that an unreadable value does not stay silent.
        date_value = meta.get("date")
        if date_value is not None and _age_days(date_value) is None:
            verdict.drift(
                f"{rel}: date '{date_value}' is not a readable date",
                "An unreadable value is a finding, not a reason to skip the check.",
            )

        target = meta.get("superseded_by")
        if target and target not in by_name:
            verdict.block(f"{rel}: superseded_by points to '{target}', which does not exist")
        elif target:
            back = (_frontmatter(by_name[target]) or {}).get("supersedes")
            if back != rel:
                verdict.drift(
                    f"{rel} -> {target}: the supersession is not mutual",
                    "Whoever supersedes is superseded — otherwise only one direction finds the successor.",
                )

        # `supersedes` is a pointer of its own, and a checked one — not just the
        # back-reference for the mutuality check above. It is resolved against
        # the repo root, not against the artefact set `by_name`: the one living
        # pointer in the repo deliberately points into docs/journal/, outside
        # plans/.
        supersedes = meta.get("supersedes")
        if supersedes and not (REPO / supersedes).exists():
            verdict.block(f"{rel}: supersedes points to '{supersedes}', which does not exist")

        # State coupling artefact <-> bead (AK-5, spec.md D3): both directions
        # are DRIFT, not BLOCK -- `bd close` typically runs AFTER the merge, so
        # a BLOCK here would hit not the commit that caused it but the next
        # uninvolved pull request. Only what lies under changes/ is checked
        # (active or archived) -- a living capability spec under specs/ is
        # never archived, per _README.md, and has no equivalent target for
        # "bead closed".
        if in_changes and meta.get("bead"):
            beads_mit_artefakt.add(str(meta["bead"]))

        if bead_statuses is not None and in_changes:
            bead = meta.get("bead")
            if bead:
                status = bead_statuses.get(bead)
                if status is None:
                    # The bead does not appear in the export at all: it may be a
                    # freshly created task (export not caught up yet) or a typo
                    # in the frontmatter. Both are unchecked, and the moving
                    # side is the tracker export -- so DRIFT, not BLOCK, and
                    # armed only under --strict like the rest of this coupling.
                    verdict.drift(
                        f"{rel}: bead '{bead}' does not appear in the tracker render {_anzeige(export_path)}",
                        "Unchecked whether artefact and bead state contradict each other.",
                    )
                else:
                    closed = status == "closed"
                    done = meta.get("implementation_status") == "done"
                    if closed and not (done and archived):
                        verdict.drift(
                            f"{rel}: bead '{bead}' is closed in the export, "
                            "but the artefact is not 'done' and archived",
                            "The tracker says finished, the artefact contradicts.",
                        )
                    if done and not closed:
                        verdict.drift(
                            f"{rel}: implementation_status is 'done', but bead "
                            f"'{bead}' is not closed in the export (status: '{status}')",
                            "The artefact says finished, the tracker contradicts.",
                        )

    # Reverse direction of the coupling: bead -> artefact.
    #
    # The loop above runs over artefacts and asks each for its bead. A bead that
    # never got an artefact lies outside its range and cannot produce a
    # finding -- for it the check is not bypassed, it is empty.
    #
    # The two RB-G7 guards above do not cover this, and rightly so: they secure
    # the two sets this function *reads* (export empty, zero artefacts). The
    # empty set of a *relation*, however, is neither of the two inputs but their
    # difference. Securing both sides against emptiness does not secure the
    # relation between them.
    #
    # Only `in_progress`: an open bead legitimately has no artefact -- it is not
    # being worked on. A closed one may be older than the workflow.
    # `in_progress` is the claim "someone is working on this right now", and the
    # workflow says that work runs through a change folder
    # (docs/WORKFLOW.md: the entry is `make change NAME=... BEAD=...`).
    #
    # DRIFT like the rest of this coupling: `bd update --status in_progress`
    # runs without a commit in this repo, often in another session. A BLOCK
    # would hit the next uninvolved pull request, not the one that caused the
    # state.
    if bead_statuses is not None:
        laufend = {bid for bid, st in bead_statuses.items() if st == "in_progress"}
        if not laufend:
            # RB-G7 for this check itself: no running beads does not mean
            # "checked and clean", but "nothing was there to check". That is
            # named, not passed over in silence -- otherwise green here reads
            # like a result.
            verdict.info(
                "no bead is 'in_progress'",
                "The reverse direction of the coupling had nothing to measure.",
            )
        else:
            ohne = sorted(laufend - beads_mit_artefakt)
            ramp = _bestand_ramp(set(ohne))
            for bid in ohne:
                verdict.drift(
                    f"Bead '{bid}' is 'in_progress' but has no artefact under plans/changes/",
                    "The tracker says work is going on here; the workflow never heard of it. "
                    "Fix: `make change NAME=<name> BEAD=" + bid + "` -- or set the bead "
                    "back to 'open' if nobody is working on it.",
                    ramp=ramp if bid in BESTAND_OHNE_ARTEFAKT else None,
                )
            verdict.info(
                f"{len(laufend)} running beads checked, {len(ohne)} without artefact",
            )

    # The index is generated and tracked — so it belongs in the same check as
    # every other rendered file: `X == render(Y)`, otherwise it ages like any
    # hand-kept list, only less conspicuously.
    #
    # BLOCK, not DRIFT. By _verdict.py the levels distinguish who caused the
    # finding: DRIFT is for a counterpart that moves here without a commit,
    # BLOCK for artefacts of this repo that contradict one another. Index and
    # inputs both live here and both move by commit — the contradiction is
    # always the consequence of the commit that creates it, and belongs at its
    # pull request. Reported as DRIFT it would be exit 0 without `--strict`,
    # and the CI step runs without `--strict`: the gate would stand green over
    # an ageing index.
    if INDEX.exists():
        if INDEX.read_text(encoding="utf-8") != render_index():
            verdict.block(
                "plans/INDEX.md deviates from its inputs",
                "Fix: make index",
            )
    else:
        verdict.block("plans/INDEX.md missing", "Fix: make index")

    if found:
        verdict.info(f"{len(found)} artefacts checked")
    return verdict


def render_index() -> str:
    rows = []
    for path in artefacts():
        meta = _frontmatter(path) or {}
        rel = str(path.relative_to(PLANS))
        rows.append(
            f"| [`{rel}`]({rel}) | {meta.get('status', '—')} | "
            f"{meta.get('implementation_status', '—')} | {meta.get('last_reviewed', '—')} | "
            f"{meta.get('bead', '—')} |"
        )
    if not rows:
        rows.append("| _no artefact yet_ | — | — | — | — |")
    return INDEX_HEADER + "\n".join(rows) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="report hygiene, write nothing")
    mode.add_argument("--index", action="store_true", help="regenerate plans/INDEX.md")
    parser.add_argument("--strict", action="store_true", help="DRIFT blocks as well")
    args = parser.parse_args(argv)

    if args.index:
        INDEX.write_text(render_index(), encoding="utf-8")
        print(f"written: {INDEX.relative_to(REPO)}")
        return 0

    verdict = check()
    print(verdict.render())
    return verdict.exit_code(strict=args.strict)


if __name__ == "__main__":
    sys.exit(main())
