def test_catalog_matches_declared_gates() -> None:
    """Criterion 1: the committed inventory holds every declared gate, exactly once, field by field."""
    alle = gates()
    rows = _rows(_generated_block(CATALOG.read_text(encoding="utf-8")))
    assert len(rows) == len(alle), f"{len(rows)} rows for {len(alle)} declared gates"
    assert _drift(alle, rows) == []


def test_catalog_renders_commands_and_actions() -> None:
    """Criterion 1, the rendering contract: hosted actions are not local commands, cells hold."""
    block = catalog_rows(_fixture_gates())
    nach_id = {r["id"]: r for r in _rows(block)}

    hosted = nach_id["probe-hosted"]
    assert hosted["command / action"] == "action `acme/probe-action@v1` (hosted CI only)", (
        "a hosted-only action must not read as a locally runnable command"
    )
    equival = nach_id["probe-equivalent"]
    assert "action `acme/probe-action@v2`" in equival["command / action"]
    assert 'locally: `npx --yes probe-cli "**/*.md"`' in equival["command / action"]

    # A pipe and a newline in cell content may not open extra cells or rows.
    pipig = [{**_fixture_gates()[0], "name": "a | b", "reason": "first line\nsecond line"}]
    zeilen = [z for z in catalog_rows(pipig).splitlines() if z.strip()]
    assert len(zeilen) == 3, "a newline in a cell broke the table into two rows"
    rows = _rows("\n".join(zeilen))
    assert rows[0]["title"] == "a | b", "the pipe must survive escaped"
    assert rows[0]["reason"] == "first line second line", "the newline must not break the row"
    # Freshly regenerated multiline metadata is not drift (phase-6 row F6-1).
    assert _drift(pipig, rows) == [], "a regenerated multiline value reads as drift"


def test_catalog_drift_is_rejected() -> None:
    """Criterion 2: a mutated inventory or a changed declaration leaves the comparison red.

    Each case plants the fault the spec refutes with, on fixture data; the
    first assertion is the counter-check that the comparator itself is green
    on a clean render.
    """
    alle = _fixture_gates()
    rows = _rows(catalog_rows(alle))
    assert _drift(alle, rows) == [], "the clean render must pass its own comparison"

    assert _drift(alle, rows[:2]) == ["missing row: probe-equivalent"]

    fremd = {**rows[0], "id": "probe-foreign"}
    assert _drift(alle, [*rows, fremd]) == ["extra row: probe-foreign"]
    assert _drift(alle, [*rows, rows[0]]) == ["duplicate row: probe-command"]

    gelogen = {**rows[1], "enforcement": "block"}
    assert _drift(alle, [rows[0], gelogen, rows[2]]) == [
        "probe-hosted: enforcement reads 'block', the gate declares 'advisory'"
    ]
